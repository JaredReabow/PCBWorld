def test_overlapping_zones_are_all_reported_never_one_hidden_net(
    engine_factory, board_dir,
):
    """A point in two pours must name both; naming one would hide the other."""
    board = sb.write_board(
        board_dir / "overlap.kicad_pcb",
        pads=[sb.Pad("PA1", 10.0, 10.0, 1), sb.Pad("PA2", 12.0, 12.0, 2)],
        zones=[
            sb.Zone(net=1, x0=0.0, y0=0.0, x1=20.0, y1=20.0,
                    fill_points=((0.0, 0.0), (20.0, 0.0), (20.0, 20.0), (0.0, 20.0))),
            sb.Zone(net=2, x0=5.0, y0=5.0, x1=15.0, y1=15.0,
                    fill_points=((5.0, 5.0), (15.0, 5.0), (15.0, 15.0), (5.0, 15.0))),
        ],
        nets=(1, 2), width=25.0, height=25.0,
    )
    engine = engine_factory(board)
    top = engine.layer_map.board_layer_order[0]

    rows = engine.get_zone_point_hits(((10.0, 10.0, top), (18.0, 18.0, top), (23.0, 23.0, top)))

    assert [row.query_index for row in rows] == [0, 1, 2]

    both = rows[0]
    assert both.status == "resolved"
    assert both.classification == "fill_multi_net"
    assert both.fill_net_code == -1, "a conflict must not be resolved to one net"
    assert sorted(hit.net_code for hit in both.hits) == [1, 2]
    assert all(hit.in_fill and hit.distance_mm == 0.0 for hit in both.hits)

    single = rows[1]
    assert single.classification == "fill_single_net"
    assert single.fill_net_code == 1
    assert [hit.net_code for hit in single.hits] == [1]

    outside = rows[2]
    assert outside.status == "resolved"
    assert outside.classification == "no_zone"
    assert list(outside.hits) == []


def test_a_void_inside_a_pour_is_outline_only_with_real_distance(
    engine_factory, board_dir,
):
    """The gap a foreign pour leaves around existing copper is the whole point."""
    board = sb.write_board(
        board_dir / "void.kicad_pcb",
        pads=[sb.Pad("PA1", 10.0, 10.0, 1)],
        zones=[sb.Zone(
            net=1, x0=0.0, y0=0.0, x1=20.0, y1=20.0,
            fill_points=((5.0, 5.0), (15.0, 5.0), (15.0, 15.0), (5.0, 15.0)))],
        nets=(1,), width=25.0, height=25.0,
    )
    engine = engine_factory(board)
    top = engine.layer_map.board_layer_order[0]

    filled, in_void, outside = engine.get_zone_point_hits(
        ((10.0, 10.0, top), (10.0, 2.0, top), (23.0, 23.0, top)))

    assert filled.classification == "fill_single_net"
    assert filled.hits[0].in_fill is True
    assert filled.hits[0].distance_mm == pytest.approx(0.0)

    # Inside the zone outline, outside its copper: a void, measured.
    assert in_void.classification == "outline_only"
    assert in_void.hits[0].in_outline is True
    assert in_void.hits[0].in_fill is False
    # 3 mm straight below the fill's y=5 edge, so the distance is axial and exact.
    assert in_void.hits[0].distance_mm == pytest.approx(3.0, abs=1e-6)
    assert in_void.fill_provenance == "loaded_unverified"

    assert outside.classification == "no_zone"


