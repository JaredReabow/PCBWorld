def test_a_measured_opening_places_the_via_where_it_was_measured(
    engine_factory, board_dir,
):
    """The family's whole claim: the via lands at the measured point.

    A layer-changing waypoint is what controls this - the session emits
    ``make_via`` at the waypoint's own coordinate, and the arrival tolerance is
    the via's radius. This pins the end-to-end behaviour the family is built on,
    including that the opening is clear of the foreign pour that covers the other
    half of the corridor.
    """
    board = sb.write_board(
        board_dir / "via_at_opening.kicad_pcb",
        pads=[sb.Pad("PA1", 2.0, 10.0, 1, kind="smd_top"),
              sb.Pad("PA2", 30.0, 10.0, 1, kind="smd_bottom")],
        zones=[sb.Zone(net=2, x0=0.0, y0=0.0, x1=14.0, y1=20.0, layer="B.Cu",
                       fill_points=((0.0, 0.0), (14.0, 0.0), (14.0, 20.0), (0.0, 20.0)))],
        nets=(1, 2), width=34.0, height=22.0,
    )
    engine = engine_factory(board)
    session = _session(engine, board)
    coverage = zc.ZoneCoverage(session)
    openings = zc.find_openings(
        coverage, (2.0, 10.0, 1), (30.0, 10.0, 2), 1,
        margin_mm=0.4, search_mm=3.0, pitch_mm=1.0, max_samples=64,
        max_openings=3, band_mm=1.0)
    assert openings

    via_radius = float(engine.route_item_radius_mm(for_via=True))
    for opening in openings:
        x_mm, y_mm, layer = opening.point
        before = engine.get_via_count()
        snap = session.snapshot()
        result = session.connect_targets(
            (2.0, 10.0, 1), (30.0, 10.0, 2), "walkaround",
            waypoints=[(x_mm, y_mm, layer)], token=snap.token)
        if not result.accepted:
            # A refused attempt is a legitimate outcome (the DRC is the
            # authority); what must never happen is copper kept that DRC refused.
            assert not result.committed
            continue
        assert engine.get_via_count() > before
        vias = [v for v in engine.get_vias()
                if math.hypot(v.x_mm - x_mm, v.y_mm - y_mm) <= via_radius + 1e-6]
        assert vias, "the via must land at the measured opening"
        break
    else:  # pragma: no cover - only if every opening is refused
        pytest.fail("no measured opening produced a kept via")


def test_screening_reports_per_edge_status_without_touching_the_board(
    engine_factory, board_dir,
):
    """The cheap pass: measure every edge, mutate nothing, bound everything."""
    board = sb.write_board(
        board_dir / "screen.kicad_pcb",
        pads=[sb.Pad("PA1", 2.0, 10.0, 1, kind="smd_top"),
              sb.Pad("PA2", 30.0, 10.0, 1, kind="smd_bottom"),
              sb.Pad("PB1", 5.0, 6.0, 2), sb.Pad("PB2", 25.0, 6.0, 2)],
        zones=[sb.Zone(net=2, x0=0.0, y0=0.0, x1=14.0, y1=20.0, layer="B.Cu",
                       fill_points=((0.0, 0.0), (14.0, 0.0), (14.0, 20.0), (0.0, 20.0)))],
        nets=(1, 2), width=34.0, height=22.0,
    )
    engine = engine_factory(board)
    session = _session(engine, board)
    coverage = zc.ZoneCoverage(session)

    cross = ((2.0, 10.0, 1), (30.0, 10.0, 2))          # needs a via hop
    same = ((5.0, 6.0, 1), (25.0, 6.0, 1))             # already on one layer
    edges = [
        (edge_key(*cross), 1),
        (edge_key(*same), 2),
        (edge_key(*cross), 1),                          # budget: max_edges = 2
    ]
    vias_before, tracks_before = engine.get_via_count(), engine.get_track_count()

    rows = zc.screen_openings(coverage, edges, margin_mm=0.4, max_edges=2,
                              pitch_mm=1.0, max_samples=64, max_openings=2, band_mm=1.0)

    statuses = [row.status for row in rows]
    assert statuses[0] == "openings", statuses
    assert statuses[1] == "same_layer"
    assert statuses[2] == "budget"
    assert rows[0].openings and rows[0].openings[0].point[2] == 2
    assert rows[0].reason == ""
    assert "max_edges" in rows[2].reason

    summary = zc.screen_summary(rows)
    assert summary["total"] == 3
    assert summary["openings"] == 1 and summary["edges_with_openings"] == 1
    assert summary["same_layer"] == 1 and summary["budget"] == 1
    assert summary["openings_total"] == len(rows[0].openings)

    # Read-only: no copper, no route, no checkpoint.
    assert engine.get_via_count() == vias_before
    assert engine.get_track_count() == tracks_before
    assert not engine.is_routing()

    # A malformed key is unknown, never silently skipped.
    broken = zc.screen_openings(coverage, [((1.0, 2.0, 1), 1)], margin_mm=0.4)
    assert broken[0].status == "unknown" and "edge key" in broken[0].reason


