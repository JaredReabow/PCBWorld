def test_openings_are_measured_clear_of_foreign_pour_and_land_on_the_far_layer(
    engine_factory, board_dir,
):
    """A cross-layer pair gets openings with real clearance, on the far layer."""
    board = sb.write_board(
        board_dir / "openings.kicad_pcb",
        pads=[sb.Pad("PA1", 2.0, 10.0, 1, kind="smd_top"),
              sb.Pad("PA2", 30.0, 10.0, 1, kind="smd_bottom")],
        # Net 2's pour covers the left half of the *far* layer: the via must
        # land clear of it, while the approach on the start layer is clear.
        zones=[sb.Zone(net=2, x0=0.0, y0=0.0, x1=14.0, y1=20.0, layer="B.Cu",
                       fill_points=((0.0, 0.0), (14.0, 0.0), (14.0, 20.0), (0.0, 20.0)))],
        nets=(1, 2), width=34.0, height=22.0,
    )
    engine = engine_factory(board)
    session = _session(engine, board)
    coverage = zc.ZoneCoverage(session)
    margin = 0.4

    openings = zc.find_openings(
        coverage, (2.0, 10.0, 1), (30.0, 10.0, 2), 1,
        margin_mm=margin, search_mm=3.0, pitch_mm=1.0, max_samples=64,
        max_openings=4, band_mm=1.0)

    assert openings, "the clear half of the corridor must offer openings"
    for opening in openings:
        x_mm, _y_mm, layer = opening.point
        assert layer == 2, "the transition layer is the far endpoint's layer"
        assert x_mm > 14.0 + margin, "no opening may sit inside net 2's pour"
        assert opening.clearance_mm >= margin
        assert opening.unknown is False
    # They are distinct places, not four names for one spot.
