"""The read-only point-in-zone query and the advisory prefilter built on it.

Two things are pinned here, and they are different claims:

* the **engine query** answers what zone geometry covers a point — every
  covering zone, its net, its fill geometry, its layer span, its keepout flags,
  and an honest (never optimistic) statement about the provenance of the fill it
  read;
* the **prefilter** turns that into a ranking signal, and its contract is that
  unknown passes through untouched, no candidate is ever dropped, and the
  transactional DRC stays the only authority. (Its engine-free policy —
  unknown/disabled handling, the margin, the ordering rule — is pinned in
  ``test_zone_prefilter_unit.py``; this file covers it against real zone
  geometry.)

All boards are generated by the repository's synthetic fixture helper.
"""

