def test_a_real_engine_ranks_a_foreign_pour_plan_last(engine_factory, board_dir):
    """The integration the prefilter exists for, on real zone geometry."""
    board = sb.write_board(
        board_dir / "rank.kicad_pcb",
        pads=[sb.Pad("PA1", 0.0, 10.0, 1), sb.Pad("PA2", 20.0, 10.0, 1),
              sb.Pad("PB1", 40.0, 10.0, 2)],
        zones=[sb.Zone(net=2, x0=25.0, y0=0.0, x1=45.0, y1=20.0, layer="F.Cu",
                       fill_points=((25.0, 0.0), (45.0, 0.0), (45.0, 20.0), (25.0, 20.0)))],
        nets=(1, 2), width=50.0, height=25.0,
    )
    engine = engine_factory(board)
    session = _session(engine, board)
    coverage = zc.ZoneCoverage(session)
    stub = _RankingStub(coverage, margin=(0.5, "test"))
    # Net 1's pair; one plan's waypoint sits in net 2's pour, the other does not.
    candidates = [_candidate("through_pour", 35.0), _candidate("clear", 20.0)]
    pair = _pair(1, (0.0, 10.0, 1), (20.0, 10.0, 1))

    ranked = RoutingRunner._zone_ranked(stub, session, pair, candidates, stub.config)

    assert [candidate.name for candidate in ranked] == ["clear", "through_pour"]
    evidence = stub.state.metrics["zone_prefilter"]
    assert evidence["available"] is True
    assert evidence["candidates_ranked_late"] == 1
    # 41 corridor samples along the pair's 20 mm leg at the configured 0.5 mm
    # pitch, plus the one waypoint that is not already on that line. The second
    # candidate reuses every corridor point from the cache instead of re-asking.
    assert evidence["stats"]["queries"] == 42
    assert evidence["stats"]["cache_hits"] >= 41
    audit = evidence["pairs"][next(iter(evidence["pairs"]))]
    assert audit[0]["candidate"] == "through_pour"
    assert audit[0]["state"] == zc.FOREIGN


