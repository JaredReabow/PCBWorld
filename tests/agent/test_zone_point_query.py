def _session(engine, board: str) -> AgentSession:
    return AgentSession(engine, board_path=board)


def _pair(net: int, start, target) -> "object":
    from pcb_world.agent.observations import NetPair

    return NetPair(
        net_code=net, net_name=sb.net_name(net), start=start, target=target,
        gap_mm=10.0, start_layers=(start[2],), target_layers=(target[2],),
        pad_groups=2,
    )


