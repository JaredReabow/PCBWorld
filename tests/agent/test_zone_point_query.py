def test_own_foreign_and_mixed_are_distinguished_by_net_and_margin(
    engine_factory, board_dir,
):
    board = sb.write_board(
        board_dir / "nets.kicad_pcb",
        pads=[sb.Pad("PA1", 10.0, 10.0, 1), sb.Pad("PA2", 12.0, 12.0, 2)],
        zones=[
            sb.Zone(net=1, x0=0.0, y0=0.0, x1=20.0, y1=20.0, layer="F.Cu",
                    fill_points=((0.0, 0.0), (20.0, 0.0), (20.0, 20.0), (0.0, 20.0))),
            sb.Zone(net=2, x0=30.0, y0=0.0, x1=40.0, y1=20.0, layer="F.Cu",
                    fill_points=((30.0, 0.0), (40.0, 0.0), (40.0, 20.0), (30.0, 20.0))),
        ],
        nets=(1, 2), width=45.0, height=25.0,
    )
    engine = engine_factory(board)
    session = _session(engine, board)
    coverage = zc.ZoneCoverage(session)

    # On net 1's pour: this is the candidate's own copper.
    assert coverage.verdict((10.0, 10.0, 1), 1, margin_mm=0.5).state == zc.OWN
    # On net 2's pour, planned for net 1: foreign.
    foreign = coverage.verdict((35.0, 10.0, 1), 1, margin_mm=0.5)
    assert foreign.state == zc.FOREIGN
    assert foreign.nets == (2,)
    # Empty space: no pour contact at all.
    assert coverage.verdict((25.0, 10.0, 1), 1, margin_mm=0.5).state == zc.NONE
    # A netless pour is nobody's own copper, so it counts as foreign.
    assert coverage.verdict((35.0, 10.0, 1), 0, margin_mm=0.5).state == zc.FOREIGN

    # The margin is what makes this a geometry test rather than a point test: a
    # 0 mm margin at a spot 0.4 mm off the pour is `none`, and the same spot
    # with the board's own copper radius + clearance is contact.
    # 0.2 mm to the right of net 2's pour edge at x=30.
    near = (29.8, 10.0, 1)
    assert coverage.verdict(near, 1, margin_mm=0.0).state == zc.NONE
    assert coverage.verdict(near, 1, margin_mm=0.5).state == zc.FOREIGN


def test_cache_lifecycle_and_refill_invalidation(engine_factory, board_dir):
    board = sb.write_board(
        board_dir / "cache.kicad_pcb",
        pads=[sb.Pad("PA1", 10.0, 10.0, 1)],
        zones=[sb.Zone(net=1, x0=0.0, y0=0.0, x1=20.0, y1=20.0,
                       fill_points=((0.0, 0.0), (20.0, 0.0), (20.0, 20.0), (0.0, 20.0)))],
        nets=(1,), width=25.0, height=25.0,
    )
    engine = engine_factory(board)
    session = _session(engine, board)
    coverage = zc.ZoneCoverage(session)

    coverage.verdict((10.0, 10.0, 1), 1, margin_mm=0.5)
    first = coverage.stats
    assert (first["queries"], first["batches"], first["cache_hits"]) == (1, 1, 0)

    # A repeated point costs no engine call — the run's per-pair loops re-ask.
    coverage.verdict((10.0, 10.0, 1), 1, margin_mm=0.5)
    second = coverage.stats
    assert second["queries"] == 1
    assert second["cache_hits"] == 1

    # ... but a *different* margin is a different question.
    coverage.verdict((10.0, 10.0, 1), 1, margin_mm=0.0)
    assert coverage.stats["queries"] == 2

    # A refill rewrites the fill polygons under the cache: the epoch moves and
    # the answer is re-fetched rather than served from before the refill.
    assert engine.zone_fill_epoch == 0
    assert engine.fill_zones("") is True
    assert engine.zone_fill_epoch == 1
    after_refill = coverage.stats["queries"]
    coverage.verdict((10.0, 10.0, 1), 1, margin_mm=0.5)
    assert coverage.stats["queries"] == after_refill + 1

    coverage.invalidate()
    assert coverage.stats["cached_points"] == 0


def test_one_point_is_own_for_one_net_and_foreign_for_another(engine_factory, board_dir):
    """The cache holds *copper*, not a verdict: the net decides own vs foreign.

    Regression for a real defect: the row cache used to hold the classified
    verdict keyed by (point, margin) only, so the second pair to ask about the
    same copper — a different net — was handed the first pair's own/foreign
    answer and mis-ranked.
    """
    board = sb.write_board(
        board_dir / "cross_net.kicad_pcb",
        pads=[sb.Pad("PA1", 10.0, 10.0, 1), sb.Pad("PA2", 12.0, 12.0, 2)],
        zones=[sb.Zone(net=2, x0=0.0, y0=0.0, x1=20.0, y1=20.0, layer="F.Cu",
                       fill_points=((0.0, 0.0), (20.0, 0.0), (20.0, 20.0), (0.0, 20.0)))],
        nets=(1, 2), width=25.0, height=25.0,
    )
    engine = engine_factory(board)
    session = _session(engine, board)
    coverage = zc.ZoneCoverage(session)
    point = (10.0, 10.0, 1)

    # Cold: one engine row, classified for net 1 (the pour is net 2).
    cold_foreign = coverage.verdict(point, 1, margin_mm=0.5)
    assert cold_foreign.state == zc.FOREIGN
    assert cold_foreign.nets == (2,)
    cold_stats = coverage.stats

    # Warm, opposite net: the row is a cache hit, and the verdict must still flip.
    warm_own = coverage.verdict(point, 2, margin_mm=0.5)
    assert warm_own.state == zc.OWN
    assert warm_own.nets == (2,)
    after = coverage.stats
    assert after["queries"] == cold_stats["queries"], "the row came from the cache"
    assert after["cache_hits"] == cold_stats["cache_hits"] + 1

    # ... and back again: alternating pairs cannot poison each other.
    assert coverage.verdict(point, 1, margin_mm=0.5).state == zc.FOREIGN
    assert coverage.verdict(point, 2, margin_mm=0.5).state == zc.OWN
    assert coverage.stats["queries"] == cold_stats["queries"]

    # The same holds through the candidate-level aggregation the runner uses.
    corridor = [((0.0, 0.0, 1), (20.0, 0.0, 1))]
    assert coverage.candidate_risk(
        [], 1, margin_mm=0.5, legs=corridor, pitch_mm=1.0, max_samples=48).state == zc.FOREIGN
    assert coverage.candidate_risk(
        [], 2, margin_mm=0.5, legs=corridor, pitch_mm=1.0, max_samples=48).state == zc.OWN


def test_a_ranked_late_candidate_can_still_miss_the_truncated_sweep(
    engine_factory, board_dir,
):
    """Ranking keeps every candidate in the list; the sweep window still cuts.

    The prefilter never removes a candidate from the generated list, but the
    runner truncates to ``candidate_limit`` *after* ranking — so a plan ranked
    late can genuinely miss this attempt. That distinction is what makes "it
    never drops a plan" false, and this test pins the real behaviour.
    """
    board = sb.write_board(
        board_dir / "truncate.kicad_pcb",
        pads=[sb.Pad("PA1", 0.0, 10.0, 1), sb.Pad("PA2", 20.0, 10.0, 1),
              sb.Pad("PB1", 30.0, 10.0, 2)],
        zones=[sb.Zone(net=2, x0=25.0, y0=0.0, x1=45.0, y1=20.0, layer="F.Cu",
                       fill_points=((25.0, 0.0), (45.0, 0.0), (45.0, 20.0), (25.0, 20.0)))],
        nets=(1, 2), width=50.0, height=25.0,
    )
    engine = engine_factory(board)
    session = _session(engine, board)
    stub = _RankingStub(zc.ZoneCoverage(session), margin=(0.5, "test"))
    pair = _pair(1, (0.0, 10.0, 1), (20.0, 10.0, 1))
    candidates = [_candidate("through_pour", 35.0), _candidate("clear_a", 10.0),
                  _candidate("clear_b", 15.0)]

    ranked = RoutingRunner._zone_ranked(stub, session, pair, candidates, stub.config)
    assert [c.name for c in ranked] == ["clear_a", "clear_b", "through_pour"]

    swept = ranked[:2]                      # candidate_limit = 2
    assert [c.name for c in swept] == ["clear_a", "clear_b"]
    assert "through_pour" not in {c.name for c in swept}


