def test_an_interior_layer_foreign_zone_disqualifies_a_four_layer_opening(
    engine_factory, board_dir,
):
    """A via's barrel and hole exist on interior layers too.

    Regression for a measured defect: the screen asked only about the two layers
    the plan changes between, so an opening could be reported clear while the via
    sat inside a foreign plane on an interior layer. On a four-layer board the
    foreign zone here lives on an *interior* layer and covers the whole corridor,
    so no opening may be offered even though both endpoint layers are clear.
    """
    def board_with(interior_zone):
        zones = []
        if interior_zone:
            zones.append(sb.Zone(net=2, x0=0.0, y0=0.0, x1=34.0, y1=22.0,
                                 layer="In1.Cu",
                                 fill_points=((0.0, 0.0), (34.0, 0.0),
                                              (34.0, 22.0), (0.0, 22.0))))
        return sb.write_board(
            board_dir / ("interior_zone.kicad_pcb" if interior_zone else "interior_clear.kicad_pcb"),
            pads=[sb.Pad("PA1", 2.0, 10.0, 1, kind="smd_top"),
                  sb.Pad("PA2", 30.0, 10.0, 1, kind="smd_bottom")],
            zones=zones, nets=(1, 2), width=34.0, height=22.0, copper_layers=4)

    blocked = engine_factory(board_with(True))
    clear = engine_factory(board_with(False))
    args = dict(margin_mm=0.4, search_mm=3.0, pitch_mm=1.0, max_samples=64,
                max_openings=3, band_mm=1.0)

    assert zc.via_layer_span(zc.ZoneCoverage(_session(blocked, board_with(True)))) == (1, 2, 3, 4)
    assert zc.find_openings(
        zc.ZoneCoverage(_session(blocked, board_with(True))),
        (2.0, 10.0, 1), (30.0, 10.0, 4), 1, **args) == []

    # The control differs only by that interior pour, and does offer openings.
    openings = zc.find_openings(
        zc.ZoneCoverage(_session(clear, board_with(False))),
        (2.0, 10.0, 1), (30.0, 10.0, 4), 1, **args)
    assert openings
    assert zc.via_layer_span(zc.ZoneCoverage(_session(clear, board_with(False)))) == (1, 2, 3, 4)


def test_the_screen_is_two_layer_compatible_and_its_queries_are_bounded(
    engine_factory, board_dir,
):
    board = sb.write_board(
        board_dir / "two_layer.kicad_pcb",
        pads=[sb.Pad("PA1", 2.0, 10.0, 1, kind="smd_top"),
              sb.Pad("PA2", 30.0, 10.0, 1, kind="smd_bottom")],
        zones=[sb.Zone(net=2, x0=0.0, y0=0.0, x1=14.0, y1=20.0, layer="B.Cu",
                       fill_points=((0.0, 0.0), (14.0, 0.0), (14.0, 20.0), (0.0, 20.0)))],
        nets=(1, 2), width=34.0, height=22.0)
    engine = engine_factory(board)
    coverage = zc.ZoneCoverage(_session(engine, board))

    # A two-layer stack is still both layers, in order.
    assert zc.via_layer_span(coverage) == (1, 2)
    vias_before, tracks_before = engine.get_via_count(), engine.get_track_count()

    max_samples = 33                   # 28 mm corridor at 1 mm pitch
    openings = zc.find_openings(
        coverage, (2.0, 10.0, 1), (30.0, 10.0, 2), 1,
        margin_mm=0.4, search_mm=3.0, pitch_mm=1.0, max_samples=max_samples,
        max_openings=3, band_mm=1.0)

    assert openings, "a two-layer board with a clear half-corridor still offers openings"
    # Bounded: at most one query per (corridor position, spanned layer), and
    # the layer-changing leg's own duplication is deduplicated before the query.
    assert coverage.stats["queries"] <= (max_samples + 1) * 2
    assert coverage.stats["cached_points"] == coverage.stats["queries"]
    # Read-only: finding openings never touches the board.
    assert engine.get_via_count() == vias_before
    assert engine.get_track_count() == tracks_before
    assert not engine.is_routing()


